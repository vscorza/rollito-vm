const SPACE_GLYPH = FONT[' '];

// Dibuja un texto a partir de (x,y) en el FB indexado, color de paleta `c`.
// Charwidth fijo de 8 px. Caracteres no soportados se renderizan como espacio.
// Clipping al rectángulo de pantalla; sin allocations.
export function drawText(fb, x, y, text, color) {
  const c = color & 0x0f;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i].toUpperCase();
    const glyph = FONT[ch] || SPACE_GLYPH;
    const cx = x + i * 8;
    if (cx + 8 <= 0 || cx >= WIDTH) continue;
    for (let r = 0; r < 8; r++) {
      const fy = y + r;
      if (fy < 0 || fy >= HEIGHT) continue;
      const row = glyph[r];
      if (row === 0) continue;
      const fbRow = fy * WIDTH;
      for (let bit = 0; bit < 8; bit++) {
        if (row & (0x80 >> bit)) {
          const fx = cx + bit;
          if (fx >= 0 && fx < WIDTH) fb[fbRow + fx] = c;
        }
      }
    }
  }
}
